_ALIASES = {
 'DSC-HX60V': 'DSC-HX60',
 'DSC-HX90V': 'DSC-HX90',
 'DSC-HX400V': 'DSC-HX400',
}

_COUNTER_A = frozenset(('ILCE-7', 'ILCE-7R', 'ILCE-7S', 'ILCE-7M2',
                       'ILCE-5000', 'ILCE-5100', 'ILCE-6000', 'ILCE-QX1'))
_COUNTER_B = frozenset(('ILCE-7RM2', 'ILCE-7SM2', 'ILCE-6300', 'ILCE-6500'))


def normalize_camera_model(model):
 """Canonicalize an actual camera model code, not a guessed marketing name."""
 name = str(model or '').strip().upper()
 return _ALIASES.get(name, name)


def get_camera_support(model):
 """Return tri-state reference eligibility without claiming physical validation."""
 name = normalize_camera_model(model)
 eligibility = True if name in PMCA_MODELS else False if name in NO_PMCA_MODELS else None
 layout = 'tag9050a' if name in _COUNTER_A else 'tag9050b' if name in _COUNTER_B else None
 return {
  'model': name,
  'pmca_apps': eligibility,
  'installation_tested': name == 'ILCE-7',
  'installation_evidence': 'RecipeLab installation confirmed on ILCE-7' if name == 'ILCE-7' else None,
  'shutter_layout': layout,
  'source': UPSTREAM_DEVICES_URL,
 }
